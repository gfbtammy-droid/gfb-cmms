import sys,os;sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from harness import *
res=[]
def ok(n,c,i=''):res.append(('PASS' if c else 'FAIL',n,i))
with sync_playwright() as p:
    br=p.chromium.launch(args=['--lang=en-GB']);ctx=new_ctx(br);pg=ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    login(pg)
    def save():pg.click('#fsave');pg.wait_for_timeout(1000)
    pg.evaluate("go('purchases');purForm()");pg.wait_for_selector('#purLines .pl');pg.fill('#f_purpose','Asset PR')
    r=pg.locator('#purLines .pl').first;r.locator('.pl-p').select_option('__asset')
    ok('category picker shows',r.locator('.pl-ab').is_visible())
    r.locator('.pl-d').fill('Mobile room sterilizer KA-MRS-24B');r.locator('.pl-q').fill('2');r.locator('.pl-r').fill('4800');u=r.locator('.pl-u');(u.select_option('UNIT') if u.evaluate("e=>e.tagName")=='SELECT' else u.fill('UNIT'))
    pg.click('text=Submit for approval');pg.wait_for_timeout(800)
    err=pg.evaluate("(document.querySelector('.sheet .ferr, .sheet .err, .sheet [role=alert]')||{}).textContent||''");ok('needs asset category','asset category' in err,err)
    r.locator('.pl-ac').select_option(index=1);pg.click('text=Submit for approval');pg.wait_for_timeout(1000)
    pid=pg.evaluate("Object.keys(S.purchases).find(k=>S.purchases[k].purpose==='Asset PR')")
    l=pg.evaluate(f"S.purchases['{pid}'].lines[0]");ok('line saved as asset',l.get('kind')=='asset' and l.get('acat'),l)
    pg.evaluate(f"purDecide('{pid}','Approved')");pg.wait_for_timeout(400);save()
    pg.evaluate(f"poForm('{pid}')");pg.wait_for_timeout(500)
    if pg.locator('#f_supplierId').count() and not pg.input_value('#f_supplierId'):pg.select_option('#f_supplierId','sup-d4')
    save();n0=pg.evaluate("Object.keys(S.assets).length")
    pg.evaluate(f"recvForm('{pid}')");pg.wait_for_timeout(500);ok('receive note',"Creates one asset per unit" in pg.inner_text('.sheet'));pg.fill('#f_doNo','DO-77');save();pg.wait_for_timeout(1500)
    n1=pg.evaluate("Object.keys(S.assets).length");ok('2 assets created',n1-n0==2,n1-n0)
    l=pg.evaluate(f"S.purchases['{pid}'].lines[0]");ok('line linked to assets',len(l.get('assetIds',[]))==2,l.get('assetIds'))
    a=pg.evaluate(f"S.assets[S.purchases['{pid}'].lines[0].assetIds[0]]");ok('asset fields',a['code'].startswith('AST-PO') and a['supplierId']=='sup-d4' and 'DO-77' in a['notes'] and a['status']=='Active',a)
    pg.evaluate(f"openDetail('purchase','{pid}')");pg.wait_for_timeout(500);ok('detail shows asset codes',a['code'] in pg.inner_text('body'))
    pg.screenshot(path=os.path.join(os.path.dirname(os.path.abspath(__file__)),'out','asset_po.png'))
    print('errors',errs)
for r in res:print(*r)
