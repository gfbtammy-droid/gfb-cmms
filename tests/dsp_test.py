    # second report cancel -> revert
    pg.evaluate("dspForm(null,{assetId:'as3',reason:'Lost / cannot be found'})");pg.wait_for_selector('#f_damageDesc');pg.fill('#f_damageDesc','Missing since stock take');pg.fill('#f_picName','Store');save()
