    ok('asset Damaged',pg.evaluate("S.assets.as8.status")=='Damaged')
    pg.click('#dspC');pg.wait_for_timeout(500)
    t=pg.evaluate("[...document.querySelectorAll('.toast')].map(x=>x.textContent).join('|')");ok('complete blocked without photo','photo' in t,t[-90:])
