    pg.evaluate(f"(async()=>{{const r=S.disposals['{did}'];await put('disposals','{did}',{{...r,files:[{{id:'disposals/{did}/x.jpg',name:'x.jpg',kind:'Photo – damage',ct:'image/jpeg',size:1,at:new Date().toISOString(),by:'t'}}]}},'Attached')}})()");pg.wait_for_timeout(600)
